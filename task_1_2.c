#include <stdio.h>

int main() {
    // 1) Вывод ФИО в квадратных скобках (длина строки 13 символов)
    printf("[Иванов И.И.]\n");
    
    // 2) Выравнивание по центру относительно длины скобок из первой строки
    printf("   Иванов  \n");
    
    // 3) Выравнивание по правому краю относительно длины скобок (ширина 12)
    printf("%12s\n", "И.И.");
    
    // 4) Зеркальное отражение первой строки
    printf("]И.И. Иванов[\n");
    
    return 0;
}